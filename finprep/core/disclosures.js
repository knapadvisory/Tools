/* ---------------------------------------------------------------------------
 * Helpers.
 * ------------------------------------------------------------------------*/

/** All disclosures attached to a statement line id. */
export const byLine = (lineId) => DISCLOSURES.filter((d) => d.lineId === lineId);

/** All disclosures applicable to a division ('I' | 'II'), including 'BOTH'. */
export const forDivision = (div) =>
  DISCLOSURES.filter((d) => d.division === div || d.division === 'BOTH');

/** All disclosures for a statement ('BS' | 'PL' | 'GENERAL'). */
export const forStatement = (statement) =>
  DISCLOSURES.filter((d) => d.statement === statement);

/** Classification hints for a line id, or an empty array. */
export const hintsFor = (lineId) => {
  const h = CLASSIFICATION_HINTS.find((x) => x.lineId === lineId);
  return h ? h.hints : [];
};

/** A single disclosure by its stable id. */
export const disclosure = (id) => DISCLOSURES.find((d) => d.id === id) || null;

/** Disclosures that carry a condition — i.e. required only in some fact patterns. */
export const conditionalDisclosures = () => DISCLOSURES.filter((d) => d.conditional !== null);
